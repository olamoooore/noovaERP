<?php

namespace Modules\EventManagement\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;

class FraudDetectionRule extends Model
{
    use HasFactory, SoftDeletes;

    protected $fillable = [
        'tenant_id',
        'rule_name',
        'rule_type',
        'description',
        'conditions',
        'actions',
        'priority',
        'is_active',
        'trigger_count',
        'last_triggered_at',
    ];

    protected $casts = [
        'conditions' => 'array',
        'actions' => 'array',
        'is_active' => 'boolean',
        'last_triggered_at' => 'datetime',
    ];

    // Rule type constants
    public const TYPE_VELOCITY = 'velocity';
    public const TYPE_PATTERN = 'pattern';
    public const TYPE_THRESHOLD = 'threshold';
    public const TYPE_ANOMALY = 'anomaly';
    public const TYPE_BLACKLIST = 'blacklist';

    // Action constants
    public const ACTION_BLOCK = 'block';
    public const ACTION_FLAG = 'flag';
    public const ACTION_RATE_LIMIT = 'rate_limit';
    public const ACTION_MANUAL_REVIEW = 'manual_review';
    public const ACTION_IDENTITY_VERIFICATION = 'identity_verification';
    public const ACTION_ALERT = 'alert';

    /**
     * Get the fraud alerts generated by this rule.
     */
    public function fraudAlerts(): HasMany
    {
        return $this->hasMany(FraudAlert::class);
    }

    /**
     * Scope to filter by tenant.
     */
    public function scopeForTenant($query, string $tenantId)
    {
        return $query->where('tenant_id', $tenantId);
    }

    /**
     * Scope to get active rules only.
     */
    public function scopeActive($query)
    {
        return $query->where('is_active', true);
    }

    /**
     * Scope to filter by rule type.
     */
    public function scopeOfType($query, string $type)
    {
        return $query->where('rule_type', $type);
    }

    /**
     * Scope to order by priority (highest first).
     */
    public function scopeByPriority($query)
    {
        return $query->orderBy('priority', 'desc');
    }

    /**
     * Check if this rule should be evaluated for the given context.
     */
    public function shouldEvaluate(array $context): bool
    {
        if (!$this->is_active) {
            return false;
        }

        // Check if context matches rule conditions
        $conditions = $this->conditions;
        
        if (isset($conditions['event_types']) && isset($context['event_type'])) {
            if (!in_array($context['event_type'], $conditions['event_types'])) {
                return false;
            }
        }

        if (isset($conditions['customer_types']) && isset($context['customer_type'])) {
            if (!in_array($context['customer_type'], $conditions['customer_types'])) {
                return false;
            }
        }

        return true;
    }

    /**
     * Evaluate this rule against the provided data.
     */
    public function evaluate(array $data): array
    {
        $result = [
            'triggered' => false,
            'risk_score' => 0,
            'evidence' => [],
            'recommended_actions' => [],
        ];

        switch ($this->rule_type) {
            case self::TYPE_VELOCITY:
                $result = $this->evaluateVelocityRule($data);
                break;
            case self::TYPE_PATTERN:
                $result = $this->evaluatePatternRule($data);
                break;
            case self::TYPE_THRESHOLD:
                $result = $this->evaluateThresholdRule($data);
                break;
            case self::TYPE_ANOMALY:
                $result = $this->evaluateAnomalyRule($data);
                break;
            case self::TYPE_BLACKLIST:
                $result = $this->evaluateBlacklistRule($data);
                break;
        }

        if ($result['triggered']) {
            $this->recordTrigger();
        }

        return $result;
    }

    /**
     * Evaluate velocity-based rule.
     */
    private function evaluateVelocityRule(array $data): array
    {
        $conditions = $this->conditions;
        $result = ['triggered' => false, 'risk_score' => 0, 'evidence' => [], 'recommended_actions' => []];

        // Check booking velocity per customer
        if (isset($conditions['max_bookings_per_customer']) && isset($data['customer_id'])) {
            $timeWindow = $conditions['time_window_minutes'] ?? 60;
            $maxBookings = $conditions['max_bookings_per_customer'];
            
            $recentBookings = BookingVelocityLog::forTenant($data['tenant_id'])
                ->forCustomer($data['customer_id'])
                ->ofType(BookingVelocityLog::ACTION_BOOKING_ATTEMPT)
                ->withinTimeWindow($timeWindow)
                ->count();

            if ($recentBookings >= $maxBookings) {
                $result['triggered'] = true;
                $result['risk_score'] = min(100, ($recentBookings / $maxBookings) * 50);
                $result['evidence'][] = "Customer made {$recentBookings} booking attempts in {$timeWindow} minutes";
                $result['recommended_actions'] = $this->actions;
            }
        }

        // Check booking velocity per IP
        if (isset($conditions['max_bookings_per_ip']) && isset($data['ip_address'])) {
            $timeWindow = $conditions['time_window_minutes'] ?? 60;
            $maxBookings = $conditions['max_bookings_per_ip'];
            
            $recentBookings = BookingVelocityLog::forTenant($data['tenant_id'])
                ->forIpAddress($data['ip_address'])
                ->ofType(BookingVelocityLog::ACTION_BOOKING_ATTEMPT)
                ->withinTimeWindow($timeWindow)
                ->count();

            if ($recentBookings >= $maxBookings) {
                $result['triggered'] = true;
                $result['risk_score'] = max($result['risk_score'], min(100, ($recentBookings / $maxBookings) * 60));
                $result['evidence'][] = "IP address made {$recentBookings} booking attempts in {$timeWindow} minutes";
                $result['recommended_actions'] = array_unique(array_merge($result['recommended_actions'], $this->actions));
            }
        }

        return $result;
    }

    /**
     * Evaluate pattern-based rule.
     */
    private function evaluatePatternRule(array $data): array
    {
        $conditions = $this->conditions;
        $result = ['triggered' => false, 'risk_score' => 0, 'evidence' => [], 'recommended_actions' => []];

        // Check for suspicious patterns
        if (isset($conditions['patterns'])) {
            foreach ($conditions['patterns'] as $pattern) {
                if ($this->matchesPattern($data, $pattern)) {
                    $result['triggered'] = true;
                    $result['risk_score'] += $pattern['risk_score'] ?? 25;
                    $result['evidence'][] = $pattern['description'] ?? 'Suspicious pattern detected';
                }
            }
            
            if ($result['triggered']) {
                $result['recommended_actions'] = $this->actions;
                $result['risk_score'] = min(100, $result['risk_score']);
            }
        }

        return $result;
    }

    /**
     * Evaluate threshold-based rule.
     */
    private function evaluateThresholdRule(array $data): array
    {
        $conditions = $this->conditions;
        $result = ['triggered' => false, 'risk_score' => 0, 'evidence' => [], 'recommended_actions' => []];

        // Check ticket quantity threshold
        if (isset($conditions['max_tickets_per_booking']) && isset($data['tickets_requested'])) {
            $maxTickets = $conditions['max_tickets_per_booking'];
            
            if ($data['tickets_requested'] > $maxTickets) {
                $result['triggered'] = true;
                $result['risk_score'] = min(100, ($data['tickets_requested'] / $maxTickets) * 40);
                $result['evidence'][] = "Requested {$data['tickets_requested']} tickets (max: {$maxTickets})";
                $result['recommended_actions'] = $this->actions;
            }
        }

        return $result;
    }

    /**
     * Evaluate anomaly-based rule.
     */
    private function evaluateAnomalyRule(array $data): array
    {
        // Placeholder for anomaly detection logic
        return ['triggered' => false, 'risk_score' => 0, 'evidence' => [], 'recommended_actions' => []];
    }

    /**
     * Evaluate blacklist-based rule.
     */
    private function evaluateBlacklistRule(array $data): array
    {
        $conditions = $this->conditions;
        $result = ['triggered' => false, 'risk_score' => 0, 'evidence' => [], 'recommended_actions' => []];

        // Check IP blacklist
        if (isset($conditions['blacklisted_ips']) && isset($data['ip_address'])) {
            if (in_array($data['ip_address'], $conditions['blacklisted_ips'])) {
                $result['triggered'] = true;
                $result['risk_score'] = 90;
                $result['evidence'][] = "IP address is blacklisted";
                $result['recommended_actions'] = $this->actions;
            }
        }

        // Check email domain blacklist
        if (isset($conditions['blacklisted_domains']) && isset($data['email'])) {
            $domain = substr(strrchr($data['email'], "@"), 1);
            if (in_array($domain, $conditions['blacklisted_domains'])) {
                $result['triggered'] = true;
                $result['risk_score'] = max($result['risk_score'], 70);
                $result['evidence'][] = "Email domain is blacklisted";
                $result['recommended_actions'] = array_unique(array_merge($result['recommended_actions'], $this->actions));
            }
        }

        return $result;
    }

    /**
     * Check if data matches a specific pattern.
     */
    private function matchesPattern(array $data, array $pattern): bool
    {
        // Implement pattern matching logic based on pattern configuration
        // This is a simplified example
        
        if (isset($pattern['field']) && isset($pattern['operator']) && isset($pattern['value'])) {
            $fieldValue = $data[$pattern['field']] ?? null;
            
            switch ($pattern['operator']) {
                case 'equals':
                    return $fieldValue === $pattern['value'];
                case 'contains':
                    return strpos($fieldValue, $pattern['value']) !== false;
                case 'greater_than':
                    return $fieldValue > $pattern['value'];
                case 'less_than':
                    return $fieldValue < $pattern['value'];
            }
        }

        return false;
    }

    /**
     * Record that this rule was triggered.
     */
    private function recordTrigger(): void
    {
        $this->increment('trigger_count');
        $this->update(['last_triggered_at' => now()]);
    }

    /**
     * Get the rule effectiveness score.
     */
    public function getEffectivenessScore(): float
    {
        if ($this->trigger_count === 0) {
            return 0;
        }

        // Calculate based on trigger frequency and accuracy
        // This is a simplified calculation
        $recentTriggers = $this->fraudAlerts()
            ->where('created_at', '>=', now()->subDays(30))
            ->count();

        $falsePositives = $this->fraudAlerts()
            ->where('created_at', '>=', now()->subDays(30))
            ->where('status', 'false_positive')
            ->count();

        if ($recentTriggers === 0) {
            return 0;
        }

        $accuracy = ($recentTriggers - $falsePositives) / $recentTriggers;
        return $accuracy * 100;
    }
}