<?php

namespace App\Accounting\Enums;

/**
 * Canonical reason codes for negative states and blocking decisions.
 * ADR-005 §29 — every material negative state must retain a deterministic reason code.
 */
enum ReasonCode: string
{
    // Period
    case PERIOD_CLOSED = 'PERIOD_CLOSED';
    case PERIOD_NOT_OPEN = 'PERIOD_NOT_OPEN';
    /** ACC-011 Financial Close workflow — not used by ACC-001 posting authority. */
    case SOFT_CLOSE_RESTRICTED = 'SOFT_CLOSE_RESTRICTED';

    // Approval / Workflow
    case APPROVAL_REQUIRED = 'APPROVAL_REQUIRED';
    case APPROVAL_REJECTED = 'APPROVAL_REJECTED';
    case WORKFLOW_AMBIGUOUS = 'WORKFLOW_AMBIGUOUS';
    case WORKFLOW_NOT_FOUND = 'WORKFLOW_NOT_FOUND';
    case WORKFLOW_DEPENDENCY_UNAVAILABLE = 'WORKFLOW_DEPENDENCY_UNAVAILABLE';

    // Tax
    case TAX_TOTAL_INCONSISTENT = 'TAX_TOTAL_INCONSISTENT';
    case TAX_RESULT_MISSING = 'TAX_RESULT_MISSING';
    case TAX_RESULT_STALE = 'TAX_RESULT_STALE';
    case TAX_RESULT_INVALIDATED = 'TAX_RESULT_INVALIDATED';

    // Control Account
    case CONTROL_ACCOUNT_SOURCE_NOT_ALLOWED = 'CONTROL_ACCOUNT_SOURCE_NOT_ALLOWED';
    case MANUAL_JOURNAL_BLOCKED = 'MANUAL_JOURNAL_BLOCKED';

    // Duplicate / Idempotency
    case DUPLICATE_SUSPECTED = 'DUPLICATE_SUSPECTED';
    case IDEMPOTENCY_KEY_REUSE_CONFLICT = 'IDEMPOTENCY_KEY_REUSE_CONFLICT';

    // Concurrency
    case SOURCE_VERSION_CONFLICT = 'SOURCE_VERSION_CONFLICT';
    case CONCURRENT_EDIT = 'CONCURRENT_EDIT';

    // Regulatory
    case REGULATORY_REJECTED = 'REGULATORY_REJECTED';

    // Banking / Reconciliation
    case BANK_MATCH_AMBIGUOUS = 'BANK_MATCH_AMBIGUOUS';
    case RECONCILIATION_VARIANCE = 'RECONCILIATION_VARIANCE';
    case CHECKPOINT_NOT_READY = 'CHECKPOINT_NOT_READY';

    // Reversal
    case OVER_REVERSAL_NOT_PERMITTED = 'OVER_REVERSAL_NOT_PERMITTED';
    case REVERSAL_ALREADY_COMPLETED = 'REVERSAL_ALREADY_COMPLETED';
    case ORIGINAL_NOT_REVERSIBLE = 'ORIGINAL_NOT_REVERSIBLE';
    case REVERSAL_PERIOD_BLOCKED = 'REVERSAL_PERIOD_BLOCKED';

    // Settlement
    case SETTLEMENT_REVIEW_REQUIRED = 'SETTLEMENT_REVIEW_REQUIRED';
    case PAYMENT_HOLD = 'PAYMENT_HOLD';

    // General
    case INSUFFICIENT_PERMISSION = 'INSUFFICIENT_PERMISSION';
    case ENTITLEMENT_INACTIVE = 'ENTITLEMENT_INACTIVE';
    case ENTITY_ACCESS_DENIED = 'ENTITY_ACCESS_DENIED';
    case ASSURANCE_BLOCKED = 'ASSURANCE_BLOCKED';
    case BUSINESS_RULE_VIOLATION = 'BUSINESS_RULE_VIOLATION';
    case CONFIGURATION_ERROR = 'CONFIGURATION_ERROR';
    case TECHNICAL_FAILURE = 'TECHNICAL_FAILURE';

    // Authority-gate failures (ADR-005 §8.4)
    case MISSING_PERMISSION_CONTEXT = 'MISSING_PERMISSION_CONTEXT';
    case PERMISSION_SERVICE_ERROR = 'PERMISSION_SERVICE_ERROR';
    case MISSING_TENANT_CONTEXT = 'MISSING_TENANT_CONTEXT';
    case MISSING_ACTOR = 'MISSING_ACTOR';
    case ENTITLEMENT_SERVICE_UNAVAILABLE = 'ENTITLEMENT_SERVICE_UNAVAILABLE';
    case ENTITLEMENT_SERVICE_ERROR = 'ENTITLEMENT_SERVICE_ERROR';
    case ENTITLEMENT_MISSING = 'ENTITLEMENT_MISSING';

    public function label(): string
    {
        return str_replace('_', ' ', ucfirst($this->value));
    }

    public function category(): string
    {
        return match ($this) {
            self::PERIOD_CLOSED, self::PERIOD_NOT_OPEN, self::SOFT_CLOSE_RESTRICTED => 'PERIOD',
            self::APPROVAL_REQUIRED, self::APPROVAL_REJECTED, self::WORKFLOW_AMBIGUOUS,
            self::WORKFLOW_NOT_FOUND, self::WORKFLOW_DEPENDENCY_UNAVAILABLE => 'WORKFLOW',
            self::TAX_TOTAL_INCONSISTENT, self::TAX_RESULT_MISSING, self::TAX_RESULT_STALE,
            self::TAX_RESULT_INVALIDATED => 'TAX',
            self::CONTROL_ACCOUNT_SOURCE_NOT_ALLOWED, self::MANUAL_JOURNAL_BLOCKED => 'CONTROL_ACCOUNT',
            self::DUPLICATE_SUSPECTED, self::IDEMPOTENCY_KEY_REUSE_CONFLICT => 'DUPLICATE',
            self::SOURCE_VERSION_CONFLICT, self::CONCURRENT_EDIT => 'CONCURRENCY',
            self::REGULATORY_REJECTED => 'REGULATORY',
            self::BANK_MATCH_AMBIGUOUS, self::RECONCILIATION_VARIANCE, self::CHECKPOINT_NOT_READY => 'RECONCILIATION',
            self::OVER_REVERSAL_NOT_PERMITTED, self::REVERSAL_ALREADY_COMPLETED,
            self::ORIGINAL_NOT_REVERSIBLE, self::REVERSAL_PERIOD_BLOCKED => 'REVERSAL',
            self::SETTLEMENT_REVIEW_REQUIRED, self::PAYMENT_HOLD => 'SETTLEMENT',
            self::INSUFFICIENT_PERMISSION, self::ENTITLEMENT_INACTIVE, self::ENTITY_ACCESS_DENIED => 'ACCESS',
            self::MISSING_PERMISSION_CONTEXT, self::PERMISSION_SERVICE_ERROR => 'ACCESS',
            self::MISSING_TENANT_CONTEXT, self::MISSING_ACTOR => 'ACCESS',
            self::ENTITLEMENT_SERVICE_UNAVAILABLE, self::ENTITLEMENT_SERVICE_ERROR, self::ENTITLEMENT_MISSING => 'ACCESS',
            self::ASSURANCE_BLOCKED => 'ASSURANCE',
            self::BUSINESS_RULE_VIOLATION, self::CONFIGURATION_ERROR, self::TECHNICAL_FAILURE => 'SYSTEM',
        };
    }
}
