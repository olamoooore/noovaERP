    private static function splitTaxonomyElement(string $taxonomyElement): array
    {
        if ($taxonomyElement === '') {
            return ['', ''];
        }

        if (!str_contains($taxonomyElement, ':')) {
            return ['sg-sfrs', $taxonomyElement];
        }

        [$prefix, $element] = explode(':', $taxonomyElement, 2);

        return [$prefix, $element];
    }
