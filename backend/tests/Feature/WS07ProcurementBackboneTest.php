    // -------------------------------------------------------------------------
    // FIX-04: Full chain structural proof (PO → GRN → Bill → GL)
    // -------------------------------------------------------------------------

    /** @test */
    public function test_full_procurement_chain_structural_proof(): void
    {
        // Step 1: PO → GRN. GoodsReceiptService is the sole owner.
        $grnSvc = file_get_contents(base_path('app/Services/GoodsReceiptService.php'));
        $this->assertStringContainsString('public function create(array $data)', $grnSvc, 'GoodsReceiptService has create()');
        $this->assertStringContainsString('public function confirm(GoodsReceipt $grn)', $grnSvc, 'GoodsReceiptService has confirm()');

        // Step 2: GRN confirmed → InventoryService::adjustStock(type: 'purchase')
        $this->assertStringContainsString("'purchase'", $grnSvc, "GRN confirm calls adjustStock with type: 'purchase'");

        // Step 3: Bill creation → BillService::createBill()
        $billSvc = file_get_contents(base_path('app/Services/BillService.php'));
        $this->assertStringContainsString('public function createBill(array $data, int $createdBy)', $billSvc, 'BillService has createBill()');

        // Step 4: Procurement bill → three-way match enforced
        $this->assertStringContainsString('threeWayMatchService->validate(', $billSvc, 'BillService enforces three-way match');

        // Step 5: Bill posting → VendorBillService → PostingEngine
        $postSvc = file_get_contents(base_path('app/Services/VendorBillService.php'));
        $this->assertStringContainsString('postingEngine', $postSvc, 'VendorBillService uses PostingEngine for GL');

        // Step 6: AP settlement → BillPaymentService → PostingEngine
        $paymentSvc = file_get_contents(base_path('app/Services/BillPaymentService.php'));
        $this->assertStringContainsString('PostingEngine', $paymentSvc, 'BillPaymentService uses PostingEngine for AP settlement');
        $this->assertStringContainsString('recordPayment(', $paymentSvc, 'BillPaymentService has recordPayment()');
    }

