/**
 * Issue #330 ([SALES-ODOO] Recurring invoices — extend the Sales Order
 * recurrence to invoices).
 *
 * Acceptance criteria:
 *  - A recurring schedule can generate invoices directly from the Sales Order
 *    recurrence, with auto-post and auto-send options.
 *  - Price and tax are re-resolved per run (engine-first: PricingService and
 *    the #302 SalesLineTaxResolver at the run date), and the generated
 *    invoice goes through the same create / credit-check (#326) path as a
 *    manual invoice; posting goes through PostingEngine.
 *  - Generation is idempotent: re-running for the same period never creates
 *    a second invoice.
 *
 * The schedule is created through the real HTTP route and generated by the
 * real scheduled command (sales:generate-recurring-orders).
 */
class Issue330RecurringInvoicesTest extends TenantTestCase
{
    private string $tenantId;

    private User $admin;

    private Product $product;

    protected function setUp(): void
    {
        parent::setUp();

        $this->bindTenantContextWithPermissions((string) Str::uuid());
        $this->tenantId = $this->boundTestTenant->getTenantKey();

        DB::table('public.tenants')->insertOrIgnore([
            'id' => $this->tenantId,
            'name' => 'Issue 330 Recurring Invoice Tenant',
            'email' => $this->tenantId.'@example.test',
            'created_at' => now(),
            'updated_at' => now(),
        ]);

        $this->admin = User::factory()->create();
        $this->admin->assignRole('Admin');
        DB::table('public.user_company_access')->insert([
            'user_id' => $this->admin->id,
            'tenant_id' => $this->tenantId,
            'role' => 'admin',
            'is_default' => true,
            'created_at' => now(),
            'updated_at' => now(),
        ]);

        FiscalPeriod::firstOrCreate(
            ['code' => now()->format('Y-m')],
            [
                'name' => now()->format('F Y'),
                'period_start' => now()->startOfMonth()->toDateString(),
                'period_end' => now()->endOfMonth()->toDateString(),
                'period_type' => 'monthly',
                'fiscal_year' => (int) now()->format('Y'),
                'is_locked' => false,
                'status' => 'open',
                'created_by' => $this->admin->id,
            ]
        );

        foreach ([
            'cash' => '1010',
            'bank' => '1020',
            'accounts_receivable' => '1100',
            'sales_tax_payable' => '2200',
            'sales_revenue' => '4100',
        ] as $mappingKey => $accountCode) {
            if (DB::table('account_mappings')->where('mapping_key', $mappingKey)->whereNull('document_type')->exists()) {
                continue;
            }

            DB::table('account_mappings')->insert([
                'mapping_key' => $mappingKey,
                'account_id' => DB::table('chart_of_accounts')->where('code', $accountCode)->value('id'),
                'document_type' => null,
                'is_active' => true,
                'created_at' => now(),
                'updated_at' => now(),
            ]);
        }

        $this->product = Product::factory()->create([
            'name' => 'Issue 330 Subscription',
            'sku' => 'I330-'.uniqid(),
            'price' => 100,
            'cost' => 10,
            'track_inventory' => false,
        ]);
    }

    private function customer(array $attributes = []): Customer
    {
        return Customer::factory()->create(array_merge([
            'legal_entity_id' => null,
            'payment_terms' => 30,
            'credit_limit' => null,
            'total_outstanding' => 0,
            'email' => 'billing-330@example.test',
        ], $attributes));
    }

    /**
     * A confirmed-and-invoiced source order: the subscription agreement.
     */
    private function sourceOrder(Customer $customer, array $lineAttributes = []): SalesOrder
    {
        $order = SalesOrder::create([
            'sales_order_number' => 'SO-330-'.Str::upper(Str::random(6)),
            'customer_id' => $customer->id,
            'status' => 'invoiced',
            'order_date' => now()->subMonth()->toDateString(),
            'currency' => 'USD',
            'subtotal' => 200,
            'tax_amount' => 0,
            'discount_amount' => 0,
            'total' => 200,
            'created_by' => $this->admin->id,
        ]);

        SalesOrderLine::create(array_merge([
            'sales_order_id' => $order->id,
            'line_type' => 'product',
            'description' => 'Monthly subscription',
            'product_id' => $this->product->id,
            'quantity' => 2,
            'unit_price' => 100,
            'tax_rate' => 0,
            'line_total' => 200,
        ], $lineAttributes));

        return $order;
    }

    private function scheduleInvoices(SalesOrder $source, array $payload = []): int
    {
        $response = $this->actingAs($this->admin, 'sanctum')
            ->postJson('/api/v1/sales/orders/'.$source->id.'/recurrence', array_merge([
                'interval' => 'monthly',
                'start_date' => now()->toDateString(),
                'document_type' => 'invoice',
            ], $payload));

        $response->assertStatus(201)
            ->assertJsonPath('data.document_type', 'invoice');

        return (int) $response->json('data.id');
    }

    /**
     * The cron run: no authenticated user, the real scheduled command.
     */
    private function runScheduler(): \Illuminate\Testing\PendingCommand
    {
        $this->app['auth']->forgetGuards();

        return $this->artisan('sales:generate-recurring-orders', [
            '--tenant' => $this->tenantId,
            '--as-of' => now()->toDateString(),
        ]);
    }

    public function test_invoice_schedule_generates_one_draft_invoice_per_period_through_the_invoice_path(): void
    {
        $customer = $this->customer();
        $source = $this->sourceOrder($customer);
        $recurrenceId = $this->scheduleInvoices($source);

        $this->runScheduler()->assertExitCode(0);

        $recurrence = SalesOrderRecurrence::findOrFail($recurrenceId);
        $this->assertSame(1, $recurrence->cycles_generated);
        $this->assertSame(now()->addMonthNoOverflow()->toDateString(), $recurrence->next_run_date->toDateString());
        $this->assertCount(1, $recurrence->generated_invoice_ids ?? [], 'The cycle records the invoice it generated.');

        $invoice = Invoice::query()->findOrFail($recurrence->generated_invoice_ids[0]);
        $this->assertSame($customer->id, (int) $invoice->customer_id);
        $this->assertSame('draft', $invoice->status, 'Without auto-post the invoice is left as a draft.');
        $this->assertSame(now()->toDateString(), $invoice->invoice_date->toDateString());
        $this->assertSame(200.0, round((float) $invoice->total, 2));
        $this->assertNull($invoice->journal_entry_id);

        // Same path as a manual invoice: a backing sales order linked to the
        // invoice (SalesOrderService::createInvoice -> createInvoiceInternal).
        $link = SalesInvoiceLink::query()->where('invoice_id', $invoice->id)->firstOrFail();
        $this->assertNotSame($source->id, (int) $link->sales_order_id);
        $this->assertSame($invoice->sales_order_id, $link->sales_order_id);

        // Idempotent: re-running for the same period creates nothing new.
        $this->runScheduler()->assertExitCode(0);
        $this->assertSame(1, Invoice::query()->where('customer_id', $customer->id)->count(), 'One invoice per period.');
        $this->assertSame(1, $recurrence->fresh()->cycles_generated);
    }

    public function test_price_and_tax_are_re_resolved_at_the_run_date(): void
    {
        // The SG pack's GST rows: 8% (2023) and 9% (from 2024, the default).
        $rules = [];
        foreach ((array) config('tax_packs.SG.rules', []) as $rule) {
            if (! in_array($rule['code'], ['SG-GST-9', 'SG-GST-8'], true)) {
                continue;
            }
            $rules[$rule['code']] = Tax::create([
                'name' => $rule['name'],
                'code' => $rule['code'],
                'type' => $rule['type'],
                'regime' => $rule['regime'],
                'jurisdiction' => $rule['jurisdiction'],
                'scope' => $rule['scope'],
                'treatment' => $rule['treatment'],
                'rate' => $rule['rate'],
                'is_inclusive' => (bool) $rule['is_inclusive'],
                'effective_from' => $rule['effective_from'],
                'effective_to' => $rule['effective_to'],
                'is_active' => true,
                'is_default' => $rule['code'] === 'SG-GST-9',
            ]);
        }
        $this->assertCount(2, $rules, 'The SG pack must provide the GST 9 and 8 rows.');
        Setting::setValue('tax', [
            'enabled' => true,
            'pricing_mode' => 'exclusive',
            'default_tax_id' => $rules['SG-GST-9']->id,
            'jurisdiction' => 'SG',
        ]);

        $customer = $this->customer();
        // The agreement was priced at 100 with the 2023 rate (8%).
        $source = $this->sourceOrder($customer, [
            'tax_rate' => (float) $rules['SG-GST-8']->rate,
            'tax_rule_id' => $rules['SG-GST-8']->id,
            'tax_code' => 'SG-GST-8',
            'tax_treatment' => 'standard_rated',
        ]);
        // The catalogue price has moved since.
        $this->product->update(['price' => 120]);

        $recurrenceId = $this->scheduleInvoices($source);
        $this->runScheduler()->assertExitCode(0);

        $invoiceId = SalesOrderRecurrence::findOrFail($recurrenceId)->generated_invoice_ids[0] ?? null;
        $this->assertNotNull($invoiceId);
        $line = DB::table('invoice_lines')->where('invoice_id', $invoiceId)->where('line_type', 'product')->first();

        $this->assertSame(120.0, round((float) $line->unit_price, 2), 'Price is re-resolved by the pricing engine on each run.');
        $this->assertSame((float) $rules['SG-GST-9']->rate, round((float) $line->tax_rate, 2), 'Tax is re-resolved at the run date (#302), not copied from the source order.');
        $this->assertSame((int) $rules['SG-GST-9']->id, (int) $line->tax_rule_id);
        $this->assertSame('SG-GST-9', $line->tax_code);
    }

    public function test_credit_block_creates_no_invoice_keeps_the_period_due_and_reports_the_failure(): void
    {
        Setting::setValue('sales.invoice.credit_limit_policy', 'block');
        $customer = $this->customer(['credit_limit' => 50]);
        $source = $this->sourceOrder($customer);
        $recurrenceId = $this->scheduleInvoices($source);
        $dueDate = SalesOrderRecurrence::findOrFail($recurrenceId)->next_run_date->toDateString();

        $this->runScheduler()->assertExitCode(1);

        $recurrence = SalesOrderRecurrence::findOrFail($recurrenceId);
        $this->assertSame(0, Invoice::query()->where('customer_id', $customer->id)->count(), 'A credit-blocked cycle must not leave an invoice behind (#326).');
        $this->assertSame(0, $recurrence->cycles_generated);
        $this->assertSame($dueDate, $recurrence->next_run_date->toDateString(), 'The period stays due so it is retried.');
        $this->assertSame('active', $recurrence->status);
        $this->assertStringContainsString('Credit check failed', (string) $recurrence->last_error);
    }

    public function test_auto_post_posts_through_the_posting_engine_with_a_balanced_entry(): void
    {
        $customer = $this->customer();
        $source = $this->sourceOrder($customer);
        $recurrenceId = $this->scheduleInvoices($source, ['auto_post' => true]);

        $this->runScheduler()->assertExitCode(0);

        $recurrence = SalesOrderRecurrence::findOrFail($recurrenceId);
        $invoice = Invoice::query()->findOrFail($recurrence->generated_invoice_ids[0]);

        $this->assertSame('posted', $invoice->status);
        $this->assertNotNull($invoice->journal_entry_id, 'Auto-post books the invoice through PostingEngine.');
        $totals = DB::table('journal_entry_lines')
            ->where('journal_entry_id', $invoice->journal_entry_id)
            ->selectRaw('COALESCE(SUM(debit),0) AS debit, COALESCE(SUM(credit),0) AS credit')
            ->first();
        $this->assertEqualsWithDelta((float) $totals->debit, (float) $totals->credit, 0.001, 'The entry must balance.');
        $arDebit = DB::table('journal_entry_lines')
            ->where('journal_entry_id', $invoice->journal_entry_id)
            ->where('account_id', DB::table('chart_of_accounts')->where('code', '1100')->value('id'))
            ->sum('debit');
        $this->assertEqualsWithDelta((float) $invoice->total, (float) $arDebit, 0.001, 'AR is debited with the invoice total.');
        $this->assertEqualsWithDelta(200.0, (float) $invoice->total, 0.001);
        $this->assertNull($recurrence->last_error);
    }

    public function test_auto_send_emails_the_generated_invoice_to_the_customer(): void
    {
        Mail::fake();
        app(DocumentTemplateServiceContract::class)->seedDefaults();

        $customer = $this->customer();
        $source = $this->sourceOrder($customer);
        $recurrenceId = $this->scheduleInvoices($source, ['auto_post' => true, 'auto_send' => true]);

        $this->runScheduler()->assertExitCode(0);

        $invoiceId = SalesOrderRecurrence::findOrFail($recurrenceId)->generated_invoice_ids[0];
        $delivery = InvoiceDelivery::query()->where('invoice_id', $invoiceId)->first();

        $this->assertNotNull($delivery, 'Auto-send delivers the invoice through the send bundle.');
        $this->assertSame('billing-330@example.test', $delivery->recipient);
        $this->assertSame(InvoiceDelivery::DOCUMENT_FINAL_INVOICE, $delivery->document_type);
    }

    public function test_auto_post_and_auto_send_are_only_accepted_for_invoice_schedules(): void
    {
        $source = $this->sourceOrder($this->customer());

        $this->actingAs($this->admin, 'sanctum')
            ->postJson('/api/v1/sales/orders/'.$source->id.'/recurrence', [
                'interval' => 'monthly',
                'start_date' => now()->toDateString(),
                'document_type' => 'order',
                'auto_post' => true,
            ])
            ->assertStatus(422)
            ->assertJsonValidationErrors(['auto_post']);

        // The default stays an order schedule (#151 behaviour unchanged).
        $this->actingAs($this->admin, 'sanctum')
            ->postJson('/api/v1/sales/orders/'.$source->id.'/recurrence', [
                'interval' => 'monthly',
                'start_date' => now()->toDateString(),
            ])
            ->assertStatus(201)
            ->assertJsonPath('data.document_type', 'order');
    }
}
