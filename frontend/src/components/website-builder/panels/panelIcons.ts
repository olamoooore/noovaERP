// Track if panel icons have been customized
let panelIconsCustomized = false

export function customizePanelIcons(editor: Editor) {
  // Prevent multiple calls
  if (panelIconsCustomized) return
  panelIconsCustomized = true
  
  const pn = editor.Panels
  
  // Remove unwanted buttons from options panel
  const optionsPanel = pn.getPanel('options')
  if (optionsPanel) {
    const buttons = optionsPanel.get('buttons') as any
    if (buttons) {
      // Remove preview/visibility buttons
      pn.removeButton('options', 'sw-visibility')
      pn.removeButton('options', 'preview')
      pn.removeButton('options', 'fullscreen')
      
      // Also try to find and remove by other properties
      let btnToRemove = buttons.find((b: any) => 
        b.get('id') === 'preview' || 
        b.get('command') === 'preview' || 
        b.get('command') === 'core:preview' ||
        (b.get('className') && b.get('className').includes('fa-eye')) ||
        (b.get('attributes') && b.get('attributes').title === 'Preview')
      )
      while (btnToRemove) {
        buttons.remove(btnToRemove)
        btnToRemove = buttons.find((b: any) => 
          b.get('id') === 'preview' || 
          b.get('command') === 'preview' || 
          b.get('command') === 'core:preview' ||
          (b.get('className') && b.get('className').includes('fa-eye')) ||
          (b.get('attributes') && b.get('attributes').title === 'Preview')
        )
      }
    }
  }
  
  // CSS fallback to hide preview buttons
  const style = document.createElement('style')
  style.innerHTML = `
    .gjs-pn-btn.fa-eye, 
    .gjs-pn-btn[title="Preview"], 
    .gjs-pn-btn[title="View components"] { 
      display: none !important; 
    }
  `
  document.head.appendChild(style)
  
  // Update labels for views panel buttons - ONLY change the label property
  // This preserves the button's command and other functionality
  const smBtn = pn.getButton('views', 'open-sm')
  if (smBtn) {
    smBtn.set('label', PANEL_ICONS.styleManager)
  }
  
  const tmBtn = pn.getButton('views', 'open-tm')
  if (tmBtn) {
    tmBtn.set('label', PANEL_ICONS.settings)
  }
  
  const layersBtn = pn.getButton('views', 'open-layers')
  if (layersBtn) {
    layersBtn.set('label', PANEL_ICONS.layers)
  }
  
  const blocksBtn = pn.getButton('views', 'open-blocks')
  if (blocksBtn) {
    blocksBtn.set('label', PANEL_ICONS.blocks)
  }
}

// Track if upload button has been added
let uploadButtonAdded = false

export function addUploadButton(editor: Editor) {
  // Prevent multiple calls
  if (uploadButtonAdded) return
  uploadButtonAdded = true
  
  const pn = editor.Panels
  editor.Commands.add('upload-file', {
    run: () => {
      const input = document.createElement('input')
      input.type = 'file'
      input.accept = '.html,.css,.js,.txt'
      input.multiple = true
      input.onchange = (e: any) => {
        const files = e.target.files
        if (!files) return
        Array.from(files).forEach((file: any) => {
          const reader = new FileReader()
          reader.onload = (event) => {
            const content = event.target?.result as string
            if (file.name.endsWith('.css')) editor.addStyle(content)
            else if (file.name.endsWith('.js')) {
              const wrapper = editor.getWrapper()
              if (wrapper) wrapper.append({ tagName: 'script', content, attributes: { type: 'text/javascript' } })
            } else editor.addComponents(content)
          }
          reader.readAsText(file)
        })
      }
      input.click()
    }
  })
  const optionsPanelRef = pn.getPanel('options')
  if (optionsPanelRef) {
    const buttons = optionsPanelRef.get('buttons') as any
    if (buttons && !buttons.find((b: any) => b.get('id') === 'upload-file')) {
      buttons.add({ id: 'upload-file', command: 'upload-file', className: 'fa fa-upload', attributes: { title: 'Upload HTML/CSS/JS' }, label: PANEL_ICONS.upload })
    }
  }
}


