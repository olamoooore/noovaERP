// Use only icons that have SVG definitions for search
const ALL_ICONS = Object.keys(ICON_SVGS)
const POPULAR_ICONS = ALL_ICONS

function createSvg(name: string): string {
  const path = ICON_SVGS[name]
  if (path) {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${path}</svg>`
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 24 24"><text x="12" y="16" text-anchor="middle" font-size="11" fill="currentColor">${name.charAt(0).toUpperCase()}</text></svg>`
}


// Track if icon search has been initialized
let iconSearchInitialized = false

/**
 * Add searchable icon panel - 8 columns, no labels, search functionality
 */
export function addIconSearch(editor: Editor) {
  // Prevent multiple initializations
  if (iconSearchInitialized) return
  iconSearchInitialized = true
  
  let isSetup = false

  const setupIconsPanel = () => {
    if (isSetup) return
    const container = editor.getContainer()
    if (!container) return

    // Find the Icons category
    const categories = container.querySelectorAll('.gjs-block-category')
    let foundCat: HTMLElement | null = null
    categories.forEach((cat) => {
      const title = cat.querySelector('.gjs-title')
      if (title && title.textContent?.includes('Icons')) {
        foundCat = cat as HTMLElement
      }
    })

    if (!foundCat) {
      setTimeout(setupIconsPanel, 300)
      return
    }

    const iconsCat = foundCat as HTMLElement

    // Check if already setup
    if (iconsCat.querySelector('.icons-search-wrapper')) return
    isSetup = true

    // Get or create blocks container
    let blocksC = iconsCat.querySelector('.gjs-blocks-c') as HTMLElement | null
    if (!blocksC) {
      blocksC = document.createElement('div')
      blocksC.className = 'gjs-blocks-c'
      iconsCat.appendChild(blocksC)
    }

    // Clear existing blocks
    blocksC.innerHTML = ''

    // Create wrapper for search + icons
    const wrapper = document.createElement('div')
    wrapper.className = 'icons-search-wrapper'
    wrapper.style.cssText = 'width: 100%;'

    // Search input
    const searchBox = document.createElement('div')
    searchBox.style.cssText = 'padding: 8px; border-bottom: 1px solid rgba(255,255,255,0.1);'
    const input = document.createElement('input')
    input.type = 'text'
    input.placeholder = 'Search icons...'
    input.style.cssText = 'width:100%;padding:8px 10px;border:1px solid rgba(255,255,255,0.2);border-radius:4px;background:rgba(255,255,255,0.1);color:#fff;font-size:12px;outline:none;'
    input.onfocus = () => input.style.borderColor = '#2a9d8f'
    input.onblur = () => input.style.borderColor = 'rgba(255,255,255,0.2)'
    searchBox.appendChild(input)
    wrapper.appendChild(searchBox)

    // Icons grid
    const grid = document.createElement('div')
    grid.className = 'icons-grid'
    grid.style.cssText = 'display:grid;grid-template-columns:repeat(8,1fr);gap:2px;padding:8px;max-height:300px;overflow-y:auto;'
    wrapper.appendChild(grid)

    // Insert wrapper into category
    const titleEl = iconsCat.querySelector('.gjs-title')
    if (titleEl && titleEl.nextSibling) {
      iconsCat.insertBefore(wrapper, titleEl.nextSibling)
    } else {
      iconsCat.appendChild(wrapper)
    }

    // Hide original blocks container
    blocksC.style.display = 'none'

    // Create icon block element
    const createBlock = (name: string): HTMLElement => {
      const el = document.createElement('div')
      el.className = 'icon-item'
      el.draggable = true
      el.title = name
      el.style.cssText = 'display:flex;align-items:center;justify-content:center;padding:8px;cursor:grab;border-radius:4px;transition:background 0.15s;'
      el.innerHTML = createSvg(name)
      el.onmouseenter = () => el.style.background = 'rgba(42,157,143,0.2)'
      el.onmouseleave = () => el.style.background = 'transparent'
      el.ondragstart = (e) => {
        // Use a wrapper span for better selectability
        e.dataTransfer?.setData('text/html', `<span class="lucide-icon-wrapper" style="display:inline-flex;align-items:center;justify-content:center;width:32px;height:32px;cursor:pointer;"><i data-lucide="${name}" class="w-6 h-6" style="display:inline-block;width:24px;height:24px;"></i></span>`)
      }
      el.onclick = () => {
        const selected = editor.getSelected()
        // Create a wrapper span that's easily selectable, containing the icon
        const wrapperContent = {
          type: 'default',
          tagName: 'span',
          classes: ['lucide-icon-wrapper'],
          style: { 
            display: 'inline-flex', 
            'align-items': 'center',
            'justify-content': 'center',
            width: '32px', 
            height: '32px',
            cursor: 'pointer',
          },
          components: [{
            type: 'lucide-icon',
            tagName: 'i',
            attributes: { 'data-lucide': name, class: 'w-6 h-6' },
            style: { display: 'inline-block', width: '24px', height: '24px' },
          }],
        }
        if (selected) {
          selected.append(wrapperContent)
        } else {
          editor.addComponents(wrapperContent)
        }
        const frame = editor.Canvas.getFrameEl()
        if (frame?.contentWindow) {
          const w = frame.contentWindow as any
          if (w.lucide) setTimeout(() => w.lucide.createIcons(), 50)
        }
      }
      return el
    }

    // Render icons
    const render = (icons: string[]) => {
      grid.innerHTML = ''
      icons.slice(0, 64).forEach(n => grid.appendChild(createBlock(n)))
    }

    // Initial render
    render(POPULAR_ICONS)

    // Search handler
    let timeout: ReturnType<typeof setTimeout>
    input.oninput = () => {
      clearTimeout(timeout)
      timeout = setTimeout(() => {
        const q = input.value.toLowerCase().trim()
        if (!q) render(POPULAR_ICONS)
        else render(ALL_ICONS.filter(n => n.includes(q)))
      }, 150)
    }
  }

  // Try to setup on various events
  editor.on('load', () => setTimeout(setupIconsPanel, 500))
  editor.on('block:drag:stop', () => setTimeout(setupIconsPanel, 100))

  // Also try when blocks panel opens - listen to the event instead of extending the command
  // This avoids breaking the command's stop method
  editor.on('run:open-blocks', () => {
    setTimeout(setupIconsPanel, 100)
  })

  // Fallback: try multiple times
  setTimeout(setupIconsPanel, 1000)
  setTimeout(setupIconsPanel, 2000)
  setTimeout(setupIconsPanel, 3000)
}
