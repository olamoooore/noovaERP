import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query'
import { useNavigate, useSearchParams } from 'react-router-dom'
import { Icon } from '@iconify/react'
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card'
import { Badge } from '@/components/ui/badge'
import { Button } from '@/components/ui/button'
import { findingsApi, type AiFinding } from '@/services/closeApi'
import { useToast } from '@/hooks/use-toast'
import { useState } from 'react'
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@/components/ui/select'

const riskConfig: Record<string, { label: string; variant: 'default' | 'secondary' | 'destructive' | 'outline'; class: string }> = {
  critical: { label: 'Critical', variant: 'destructive', class: 'text-red-600' },
  high:     { label: 'High',     variant: 'destructive', class: 'text-red-500' },
  medium:   { label: 'Medium',   variant: 'outline',     class: 'text-yellow-600' },
  low:      { label: 'Low',      variant: 'secondary',   class: 'text-slate-500' },
}

const statusConfig: Record<string, { label: string; variant: 'default' | 'secondary' | 'destructive' | 'outline' }> = {
  open:      { label: 'Open',      variant: 'default' },
  accepted:  { label: 'Accepted',  variant: 'outline' },
  dismissed: { label: 'Dismissed', variant: 'secondary' },
  escalated: { label: 'Escalated', variant: 'destructive' },
  edited:    { label: 'Edited',    variant: 'outline' },
}

export function AiFindingsPage() {
  const navigate = useNavigate()
  const [params] = useSearchParams()
  const reviewId = params.get('reviewId') ?? ''
  const { toast } = useToast()
  const queryClient = useQueryClient()
  const [riskFilter, setRiskFilter] = useState<string>('all')

  const { data: findings = [], isLoading } = useQuery<AiFinding[]>({
    queryKey: ['ai-findings', reviewId || 'all'],
    queryFn: () =>
      reviewId
        ? findingsApi.list(reviewId).then(r => r.data.data)
        : findingsApi.listAll().then(r => r.data.data),
  })

  function invalidate() {
    queryClient.invalidateQueries({ queryKey: ['ai-findings', reviewId] })
  }

  function makeMutation(fn: (id: string) => Promise<unknown>, label: string) {
    return useMutation({
      mutationFn: fn,
      onSuccess: () => { invalidate(); toast({ title: label }) },
      onError:   () => toast({ title: `Action failed.`, variant: 'destructive' }),
    })
  }

  // eslint-disable-next-line react-hooks/rules-of-hooks
  const acceptMutation   = makeMutation(findingsApi.accept,   'Finding accepted.')
  // eslint-disable-next-line react-hooks/rules-of-hooks
  const dismissMutation  = makeMutation(findingsApi.dismiss,  'Finding dismissed.')
  // eslint-disable-next-line react-hooks/rules-of-hooks
  const escalateMutation = makeMutation(findingsApi.escalate, 'Finding escalated.')

  const filtered = riskFilter === 'all'
    ? findings
    : findings.filter(f => f.risk_status === riskFilter)

  const openCount     = findings.filter(f => f.status === 'open').length
  const critHighCount = findings.filter(f => f.risk_status === 'critical' || f.risk_status === 'high').length

  return (
    <div className="space-y-6">
      <div className="flex items-center justify-between flex-wrap gap-3">
        <div className="space-y-1">
          <Button variant="ghost" className="px-0 h-auto py-1" onClick={() => navigate(-1)}>
            <Icon icon="solar:arrow-left-bold" className="mr-1.5 h-4 w-4" />
            Back
          </Button>
          <h1 className="text-3xl font-bold">AI Findings</h1>
          <p className="text-muted-foreground mt-1">
            AI-generated anomalies and exceptions for human review.
          </p>
        </div>
        <Select value={riskFilter} onValueChange={setRiskFilter}>
          <SelectTrigger className="w-40">
            <SelectValue placeholder="Filter risk" />
          </SelectTrigger>
          <SelectContent>
            <SelectItem value="all">All Risk Levels</SelectItem>
            {Object.entries(riskConfig).map(([k, v]) => (
              <SelectItem key={k} value={k}>{v.label}</SelectItem>
            ))}
          </SelectContent>
        </Select>
      </div>

      {/* AI Advisory Banner */}
      <div className="flex items-start gap-3 rounded-lg border border-yellow-300 bg-yellow-50 dark:bg-yellow-950/20 dark:border-yellow-700 px-4 py-3">
        <Icon icon="solar:info-circle-bold-duotone" className="h-5 w-5 text-yellow-600 flex-shrink-0 mt-0.5" />
        <p className="text-sm text-yellow-800 dark:text-yellow-300">
          <strong>Advisory only.</strong> AI findings are generated by automated analysis and must be reviewed and approved by a qualified reviewer before any action is taken. These findings do not constitute final audit conclusions.
        </p>
      </div>

      {/* Summary bar */}
      {findings.length > 0 && (
        <div className="flex items-center gap-4 flex-wrap">
          <span className="text-sm text-muted-foreground">
            <span className="font-semibold text-foreground">{findings.length}</span> findings total
          </span>
          <span className="text-sm text-muted-foreground">
            <span className="font-semibold text-foreground">{openCount}</span> open
          </span>
          {critHighCount > 0 && (
            <span className="text-sm text-red-600 font-medium flex items-center gap-1">
              <Icon icon="solar:danger-bold" className="h-4 w-4" />
              {critHighCount} critical / high risk
            </span>
          )}
        </div>
      )}

      {isLoading ? (
        <div className="flex items-center justify-center gap-2 py-16 text-muted-foreground">
          <Icon icon="solar:spinner-bold" className="h-5 w-5 animate-spin" />
          Loading findings…
        </div>
      ) : filtered.length === 0 ? (
        <Card>
          <CardContent className="py-12 text-center text-muted-foreground">
            <Icon icon="solar:check-circle-bold-duotone" className="h-10 w-10 mx-auto mb-3 opacity-40 text-green-500" />
            <p className="font-medium">No findings{riskFilter !== 'all' ? ` at ${riskFilter} risk` : ''}.</p>
          </CardContent>
        </Card>
      ) : (
        <div className="grid gap-3">
          {filtered.map(finding => {
            const risk   = riskConfig[finding.risk_status]   ?? riskConfig.low
            const status = statusConfig[finding.status]      ?? statusConfig.open
            const isOpen = finding.status === 'open'

            return (
              <Card key={finding.id} className="hover:shadow-md transition-shadow">
                <CardContent className="pt-4 pb-3">
                  <div className="space-y-3">
                    <div className="min-w-0 space-y-2">
                      <div className="flex items-center gap-2 flex-wrap">
                        <code className="text-xs bg-muted rounded px-1.5 py-0.5 font-mono">{finding.account_code}</code>
                        <Badge variant={risk.variant}>{risk.label} Risk</Badge>
                        <Badge variant={status.variant}>{status.label}</Badge>
                        <span className="text-xs text-muted-foreground">
                          {finding.finding_type.replace(/_/g, ' ')}
                        </span>
                        <span className="text-xs text-muted-foreground">
                          Confidence: <span className="font-medium text-foreground">{Math.round(finding.confidence * 100)}%</span>
                        </span>
                        <span className="text-xs text-muted-foreground">
                          Review {finding.review_id.slice(0, 8)}
                        </span>
                      </div>
                      <p className="text-sm text-foreground">{finding.description}</p>
                      {finding.likely_cause && (
                        <div className="rounded-lg border bg-muted/40 px-3 py-2">
                          <p className="text-xs font-semibold uppercase tracking-wide text-muted-foreground">Likely cause</p>
                          <p className="text-sm mt-1 text-foreground">{finding.likely_cause}</p>
                        </div>
                      )}
                      {!!finding.detail_items.length && (
                        <div className="grid gap-2 sm:grid-cols-2">
                          {finding.detail_items.map(item => (
                            <div key={`${finding.id}-${item.label}`} className="rounded-lg border px-3 py-2">
                              <p className="text-xs uppercase tracking-wide text-muted-foreground">{item.label}</p>
                              <p className="text-sm font-medium mt-1">{item.value}</p>
                            </div>
                          ))}
                        </div>
                      )}
                      {finding.recommendation && (
                        <div className="rounded-lg border border-blue-200 bg-blue-50 px-3 py-2 dark:border-blue-900 dark:bg-blue-950/30">
                          <p className="text-xs font-semibold uppercase tracking-wide text-blue-700 dark:text-blue-300">Recommended action</p>
                          <p className="text-sm mt-1 text-blue-900 dark:text-blue-100">{finding.recommendation}</p>
                        </div>
                      )}
                      {finding.accepted_at && (
                        <p className="text-xs text-muted-foreground">
                          Accepted {new Date(finding.accepted_at).toLocaleDateString()}
                          {finding.accepted_by ? ` by ${finding.accepted_by}` : ''}
                        </p>
                      )}
                      {finding.dismissed_at && (
                        <p className="text-xs text-muted-foreground">
                          Dismissed {new Date(finding.dismissed_at).toLocaleDateString()}
                          {finding.dismissed_by ? ` by ${finding.dismissed_by}` : ''}
                        </p>
                      )}
                    </div>

                    {isOpen && (
                      <div className="flex items-center justify-between gap-3 border-t pt-3 flex-wrap">
                        <div className="flex items-center gap-2 text-xs font-medium uppercase tracking-[0.18em] text-muted-foreground">
                          <Icon icon="solar:shield-check-bold-duotone" className="h-4 w-4" />
                          Reviewer actions
                        </div>
                        <div className="flex items-center gap-2 flex-wrap">
                          <Button
                            size="sm"
                            onClick={() => acceptMutation.mutate(finding.id)}
                            disabled={acceptMutation.isPending}
                          >
                            <Icon icon="solar:check-circle-bold" className="h-4 w-4" />
                            Accept
                          </Button>
                          <Button
                            size="sm"
                            variant="secondary"
                            onClick={() => dismissMutation.mutate(finding.id)}
                            disabled={dismissMutation.isPending}
                          >
                            <Icon icon="solar:close-circle-bold" className="h-4 w-4" />
                            Dismiss
                          </Button>
                          <Button
                            size="sm"
                            variant="outline"
                            className="border-orange-200 text-orange-700 hover:bg-orange-50 hover:text-orange-800 dark:border-orange-900 dark:text-orange-300 dark:hover:bg-orange-950/30"
                            onClick={() => escalateMutation.mutate(finding.id)}
                            disabled={escalateMutation.isPending}
                          >
                            <Icon icon="solar:danger-triangle-bold" className="h-4 w-4" />
                            Escalate
                          </Button>
                        </div>
                      </div>
                    )}
                  </div>
                </CardContent>
              </Card>
            )
          })}
        </div>
      )}
    </div>
  )
}
