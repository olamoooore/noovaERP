import { useQuery } from '@tanstack/react-query'
import { useSearchParams } from 'react-router-dom'
import { Icon } from '@iconify/react'
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card'
import { Badge } from '@/components/ui/badge'
import { forecastApi, type ExecutiveSummary } from '@/services/closeApi'

function StatCard({ label, value, sub, icon, iconClass }: {
  label: string
  value: string | number
  sub?: string
  icon: string
  iconClass?: string
}) {
  return (
    <Card>
      <CardContent className="pt-5 pb-4">
        <div className="flex items-start justify-between">
          <div>
            <p className="text-sm text-muted-foreground">{label}</p>
            <p className="text-3xl font-bold mt-1">{value}</p>
            {sub && <p className="text-xs text-muted-foreground mt-0.5">{sub}</p>}
          </div>
          <div className={`p-2.5 rounded-xl ${iconClass ?? 'bg-primary/10 text-primary'}`}>
            <Icon icon={icon} className="h-5 w-5" />
          </div>
        </div>
      </CardContent>
    </Card>
  )
}

export function ExecutiveSummaryPage() {
  const [params] = useSearchParams()
  const entityId = params.get('entityId') ?? 'entity-001'
  const periodId = params.get('periodId') ?? '2026-04'

  const { data: summary, isLoading } = useQuery<ExecutiveSummary>({
    queryKey: ['executive-summary', entityId, periodId],
    queryFn: () => forecastApi.executive(entityId, periodId).then(r => r.data.data),
  })

  const score = summary?.readiness_score ?? 0
  const scoreColor = score >= 80 ? 'text-green-600' : score >= 60 ? 'text-yellow-600' : 'text-red-600'

  return (
    <div className="space-y-8">
      <div>
        <h1 className="text-3xl font-bold">Executive Summary</h1>
        <p className="text-muted-foreground mt-1">
          Close status for {entityId} — {periodId}
        </p>
      </div>

      {/* AI Advisory Banner */}
      <div className="flex items-start gap-3 rounded-lg border border-yellow-300 bg-yellow-50 dark:bg-yellow-950/20 dark:border-yellow-700 px-4 py-3">
        <Icon icon="solar:info-circle-bold-duotone" className="h-5 w-5 text-yellow-600 flex-shrink-0 mt-0.5" />
        <p className="text-sm text-yellow-800 dark:text-yellow-300">
          <strong>Advisory only.</strong> This summary is generated by AI-assisted analysis and does not constitute final close authorization or an audit opinion. Authorization must be performed separately by an authorized approver.
        </p>
      </div>

      {isLoading ? (
        <div className="flex items-center justify-center gap-2 py-16 text-muted-foreground">
          <Icon icon="solar:spinner-bold" className="h-5 w-5 animate-spin" />
          Loading executive summary…
        </div>
      ) : !summary?.summary_available ? (
        <Card>
          <CardContent className="py-16 text-center text-muted-foreground">
            <Icon icon="solar:chart-bold-duotone" className="h-10 w-10 mx-auto mb-3 opacity-40" />
            <p className="font-medium">Summary not available yet.</p>
            <p className="text-sm mt-1">A summary will be available once readiness data has been generated.</p>
          </CardContent>
        </Card>
      ) : (
        <div className="space-y-8">
          {/* Hero readiness */}
          <Card>
            <CardContent className="pt-8 pb-6">
              <div className="flex flex-col md:flex-row items-start md:items-center justify-between gap-6">
                <div className="space-y-1">
                  <p className="text-sm text-muted-foreground font-medium uppercase tracking-wide">Overall Readiness</p>
                  <p className={`text-7xl font-black ${scoreColor}`}>{score}%</p>
                  {summary.generated_at && (
                    <p className="text-xs text-muted-foreground pt-1">
                      As of {new Date(summary.generated_at).toLocaleString()}
                    </p>
                  )}
                </div>
                <div className="space-y-3">
                  {score >= 100 && (summary.open_blockers ?? 0) === 0 ? (
                    <Badge className="text-base px-5 py-2 bg-green-500 hover:bg-green-600 text-white">
                      <Icon icon="solar:check-circle-bold" className="mr-2 h-5 w-5" />
                      Ready for Final Close
                    </Badge>
                  ) : (
                    <Badge variant="destructive" className="text-base px-5 py-2">
                      <Icon icon="solar:close-circle-bold" className="mr-2 h-5 w-5" />
                      Close Not Authorized
                    </Badge>
                  )}
                  {(summary.open_blockers ?? 0) > 0 && (
                    <p className="text-sm text-red-500 flex items-center gap-1.5">
                      <Icon icon="solar:danger-bold" className="h-4 w-4" />
                      {summary.open_blockers} unresolved blocker{(summary.open_blockers ?? 0) !== 1 ? 's' : ''}
                    </p>
                  )}
                  {(summary.open_findings ?? 0) > 0 && (
                    <p className="text-sm text-yellow-600 flex items-center gap-1.5">
                      <Icon icon="solar:magic-stick-3-bold-duotone" className="h-4 w-4" />
                      {summary.open_findings} open AI finding{(summary.open_findings ?? 0) !== 1 ? 's' : ''}
                    </p>
                  )}
                </div>
              </div>
            </CardContent>
          </Card>

          {/* Stats */}
          <div className="grid grid-cols-2 md:grid-cols-4 gap-4">
            <StatCard
              label="Open Blockers"
              value={summary.open_blockers ?? 0}
              icon="solar:lock-keyhole-bold-duotone"
              iconClass={(summary.open_blockers ?? 0) > 0 ? 'bg-red-500/10 text-red-500' : 'bg-green-500/10 text-green-500'}
            />
            <StatCard
              label="Open AI Findings"
              value={summary.open_findings ?? 0}
              icon="solar:magic-stick-3-bold-duotone"
              iconClass={(summary.open_findings ?? 0) > 0 ? 'bg-yellow-500/10 text-yellow-600' : 'bg-green-500/10 text-green-500'}
            />
            <StatCard
              label="Accounts Signed Off"
              value={summary.accounts_signed_off ?? 0}
              sub={`of ${summary.total_accounts ?? 0} total`}
              icon="solar:clipboard-check-bold-duotone"
              iconClass="bg-blue-500/10 text-blue-500"
            />
            <StatCard
              label="Sign-Off Coverage"
              value={(summary.total_accounts ?? 0) > 0
                ? `${Math.round(((summary.accounts_signed_off ?? 0) / (summary.total_accounts ?? 1)) * 100)}%`
                : '—'}
              icon="solar:pie-chart-2-bold-duotone"
              iconClass="bg-violet-500/10 text-violet-500"
            />
          </div>

          {/* Final note */}
          <Card className="border-dashed">
            <CardContent className="pt-5 pb-4 flex items-start gap-3">
              <Icon icon="solar:shield-warning-bold-duotone" className="h-5 w-5 text-muted-foreground flex-shrink-0 mt-0.5" />
              <p className="text-sm text-muted-foreground">
                Final close authorization requires all accounts to be signed off, zero open blockers, and a readiness score of 100%. Proceed to the <strong>Close Cycles</strong> page to authorize close once all conditions are met.
              </p>
            </CardContent>
          </Card>
        </div>
      )}
    </div>
  )
}
